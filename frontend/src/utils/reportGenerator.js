import jsPDF from 'jspdf';
import 'jspdf-autotable';

export const generatePDFReport = (data) => {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFillColor(59, 82, 255); // Primary color
  doc.rect(0, 0, pageWidth, 40, 'F');
  
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.text('AI Interview Ready Platform', 20, 25);
  
  doc.setFontSize(14);
  doc.text('Resume Analysis Report', 20, 34);

  // Score Section
  doc.setTextColor(30, 41, 59);
  doc.setFontSize(18);
  doc.text(`Overall Score: ${data.score}/100`, 20, 55);

  // Field/Role
  doc.setFontSize(12);
  doc.text(`Target Field: ${data.field || 'General'}`, 20, 65);

  // Table Data
  const sections = [
    { title: 'Detected Skills', data: data.skills },
    { title: 'Strengths', data: data.strengths },
    { title: 'Weaknesses', data: data.weaknesses },
    { title: 'Missing Keywords (ATS)', data: data.missingKeywords },
  ];

  let currentY = 75;

  sections.forEach(section => {
    if (section.data && section.data.length > 0) {
      doc.autoTable({
        startY: currentY,
        head: [[section.title]],
        body: section.data.map(item => [item]),
        theme: 'striped',
        headStyles: { fillColor: [59, 82, 255] },
        margin: { left: 20, right: 20 }
      });
      currentY = doc.lastAutoTable.finalY + 10;
    }
  });

  // Feedback Section
  if (currentY > 240) {
    doc.addPage();
    currentY = 20;
  }

  doc.setFontSize(16);
  doc.text('ATS & Grammar Feedback', 20, currentY);
  currentY += 10;

  doc.setFontSize(10);
  const atsText = doc.splitTextToSize(`ATS: ${data.atsFeedback}`, pageWidth - 40);
  doc.text(atsText, 20, currentY);
  currentY += atsText.length * 5 + 5;

  const grammarText = doc.splitTextToSize(`Grammar: ${data.grammarFeedback || data.grammar_feedback || ''}`, pageWidth - 40);
  doc.text(grammarText, 20, currentY);
  currentY += grammarText.length * 5 + 10;

  // Suggestions
  doc.setFontSize(16);
  doc.text('Improvement Suggestions', 20, currentY);
  currentY += 10;
  
  doc.setFontSize(10);
  data.suggestions.forEach(s => {
    const text = doc.splitTextToSize(`• ${s}`, pageWidth - 40);
    doc.text(text, 20, currentY);
    currentY += text.length * 5 + 2;
  });

  // Footer
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(`Generated by AI Interview Ready Platform | Page ${i} of ${pageCount}`, pageWidth / 2, doc.internal.pageSize.getHeight() - 10, { align: 'center' });
  }

  doc.save(`Analysis_Report_${new Date().getTime()}.pdf`);
};
